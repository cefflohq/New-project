const dict = { en, ms };

export function t(key, vars) {
  const s = dict[prefs.lang]?.[key] ?? en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? '')) : s;
}

export const locale = () => (prefs.lang === 'ms' ? 'ms-MY' : 'en-MY');

export function fmtTime(iso) {
  if (!iso) return '';
  return new Date(iso).toLocaleTimeString(prefs.lang === 'ms' ? 'ms-MY' : 'en-US', { hour: 'numeric', minute: '2-digit', hour12: true });
}
export function fmtDate(iso) {
  if (!iso) return '';
  const d = new Date(iso);
  return `${d.getDate()} ${d.toLocaleDateString(prefs.lang === 'ms' ? 'ms-MY' : 'en-US', { month: 'short' })} ${d.getFullYear()}`;
}
// "Wednesday, 17 Sep 2025" (reference format), localised.
export function longToday() {
  const d = new Date();
  const loc = prefs.lang === 'ms' ? 'ms-MY' : 'en-US';
  const part = o => d.toLocaleDateString(loc, o);
  return `${part({ weekday: 'long' })}, ${d.getDate()} ${part({ month: 'short' })} ${d.getFullYear()}`;
}
export function ago(iso) {
  const m = Math.round((Date.now() - new Date(iso).getTime()) / 60000);
  if (m < 1) return t('c.justNow');
  if (m < 60) return t('c.minutesAgo', { n: m });
  const h = Math.round(m / 60);
  return h === 1 ? t('c.hoursAgo', { n: h }) : t('c.hoursAgoMany', { n: h });
}
